/*
 * vfs.c
 * Virtual Filesystem Semantic Layer
 *
 * Intercepts open() / openat() / stat() / read() calls to Linux-specific
 * paths that don't exist on Windows and serves synthetic responses.
 *
 * Covered paths:
 *   /proc/self/maps       - memory map (used by GC, profilers, stack unwinding)
 *   /proc/self/exe        - symlink to our binary path
 *   /proc/self/cmdline    - argv[0]\0argv[1]\0...
 *   /proc/self/status     - process status (Name, Pid, VmRSS, etc.)
 *   /proc/cpuinfo         - CPU feature flags (HWCAP, SSE2, etc.)
 *   /proc/meminfo         - memory totals
 *   /dev/urandom          - CSPRNG (-> RtlGenRandom)
 *   /dev/random           - same
 *   /dev/null             - bit bucket
 *   /dev/zero             - zero fill
 *   /dev/dsp              - OSS audio sink (silent stub)
 *   /dev/dri/card0        - DRM GPU device (stub, GL goes through GLX bridge)
 *   /dev/input/event0..N  - evdev input (-> JVS bridge)
 *   /dev/ttyS0            - JVS serial port
 *   /sys/class/...        - sysfs device enumeration
 */

