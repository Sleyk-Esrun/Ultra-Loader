/* Linux ioctl request codes we care about */
#define TCGETS           0x5401
#define TCSETS           0x5402
#define TCSETSW          0x5403
#define TIOCGWINSZ       0x5413
#define TIOCSWINSZ       0x5414
#define FIONREAD         0x541B
#define SNDCTL_DSP_RESET       0x5000
#define SNDCTL_DSP_SETFMT      0xC0045005
#define SNDCTL_DSP_CHANNELS    0xC0045006
#define SNDCTL_DSP_SPEED       0xC0045002
#define SNDCTL_DSP_GETOSPACE   0x800C5004
#define EVIOCGVERSION          0x80044501
#define EVIOCGNAME_BASE        0x82004506  /* + len<<16 */
#define DRM_IOCTL_VERSION      0xC0406400
#define DRM_IOCTL_GET_CAP      0xC0106419

typedef struct { unsigned short ws_row, ws_col, ws_xpixel, ws_ypixel; } WinSize;

/* termios structure (Linux) */
typedef struct {
    uint32_t c_iflag, c_oflag, c_cflag, c_lflag;
    uint8_t  c_line;
    uint8_t  c_cc[19];
    uint32_t c_ispeed, c_ospeed;
} Linux_Termios;

int64_t vfs_ioctl(int fd, uint64_t req, void *arg)
{
    if (ftdi_shim_is_fd(fd)) return (int64_t)ftdi_shim_ioctl(fd, (unsigned long)req, arg);
    VfsFd *v = vfs_get(fd);
    if (!v) return -9;

    /* Throttle: the credit/EEPROM bookkeeping polls I2C every frame, flooding
     * the log (and keeping the watchdog heartbeat alive). Log the first few. */
    { static long g_ioctl_log = 40; if (g_ioctl_log > 0) { g_ioctl_log--;
        loader_log(LOG_DEBUG, "vfs_ioctl fd=%d req=0x%llx", fd, (unsigned long long)req); } }

    switch (v->type) {

    case VFS_TYPE_TTYSERIAL:
        switch (req & 0xFFFF) {
        case (TCGETS  & 0xFFFF):
        case (TCSETSW & 0xFFFF):
        case (TCSETS  & 0xFFFF):
            if (arg) memset(arg, 0, sizeof(Linux_Termios));
            return 0;
        case (FIONREAD & 0xFFFF):
            if (arg) *(int*)arg = 0;
            return 0;
        }
        return 0;

    case VFS_TYPE_DEVDSP:
        switch (req) {
        case SNDCTL_DSP_RESET:    return 0;
        case SNDCTL_DSP_SETFMT:   return 0; /* accept any format */
        case SNDCTL_DSP_CHANNELS: return 0;
        case SNDCTL_DSP_SPEED:    return 0;
        case SNDCTL_DSP_GETOSPACE:
            if (arg) {
                /* Report lots of space available */
                int *p = (int*)arg;
                p[0] = 16;      /* fragments */
                p[1] = 4096;    /* fragsize */
                p[2] = 65536;   /* bytes total */
                p[3] = 65536;   /* bytes available */
            }
            return 0;
        }
        return 0;

    case VFS_TYPE_EVDEV:
        if ((req & 0xFFFF) == (EVIOCGVERSION & 0xFFFF)) {
            if (arg) *(int*)arg = 0x010001; /* kernel input version */
            return 0;
        }
        if ((req >> 8 & 0xFF) == 0x45) { /* EVIOCGNAME */
            if (arg) snprintf((char*)arg, 64, "UltraLoader-JVS-Input-%d",
                              v->evdev_index);
            return 0;
        }
        return 0;

    case VFS_TYPE_DRM:
        /* Route to NVIDIA ioctl stub */
        return nvidia_ioctl(fd, req, arg);

    case VFS_TYPE_LBB:
        return lbb_ioctl(req, arg);

    case VFS_TYPE_I2C:
        return eeprom_ioctl(req, arg);

    default:
        return -22; /* EINVAL */
    }
}

/* ------------------------------------------------------------------ */
/* VFS lseek                                                            */
/* ------------------------------------------------------------------ */
int64_t vfs_lseek(int fd, int64_t off, int whence)
{
    VfsFd *v = vfs_get(fd);
    if (!v) return -9;
    if (v->type != VFS_TYPE_STATIC) return 0;
    switch (whence) {
    case 0: v->pos = (size_t)off; break;                         /* SEEK_SET */
    case 1: v->pos = (size_t)((int64_t)v->pos + off); break;    /* SEEK_CUR */
    case 2: v->pos = (size_t)((int64_t)v->size + off); break;   /* SEEK_END */
    }
    if (v->pos > v->size) v->pos = v->size;
    return (int64_t)v->pos;
}

/* ------------------------------------------------------------------ */
/* VFS close                                                            */
/* ------------------------------------------------------------------ */
int vfs_close(int fd)
{
    if (ftdi_shim_is_fd(fd)) return ftdi_shim_close(fd);
    VfsFd *v = vfs_get(fd);
    if (!v) return -9;
    if (v->data) free(v->data);
    memset(v, 0, sizeof(VfsFd));
    return 0;
}

/* ------------------------------------------------------------------ */
/* VFS stat (fstat on a vfd)                                           */
/* ------------------------------------------------------------------ */
int vfs_fstat(int fd, Linux_Stat *st)
{
    if (ftdi_shim_is_fd(fd)) {
        /* FT4232H channels are char devices with unknown size - glibc's
         * ttyname_r / isatty want st_mode to indicate S_IFCHR. */
        memset(st, 0, sizeof(*st));
        st->st_mode = 0020666;
        return 0;
    }
    VfsFd *v = vfs_get(fd);
    if (!v) return -9;
    memset(st, 0, sizeof(*st));
    st->st_size = (int64_t)v->size;
    switch (v->type) {
    case VFS_TYPE_DEVNULL:
    case VFS_TYPE_DEVZERO:
    case VFS_TYPE_DEVRANDOM:
    case VFS_TYPE_DEVDSP:
    case VFS_TYPE_TTYSERIAL:
    case VFS_TYPE_DRM:
    case VFS_TYPE_EVDEV:
    case VFS_TYPE_LBB:
    case VFS_TYPE_I2C:
        st->st_mode = 0020666; /* char device */
        break;
    default:
        st->st_mode = 0100444; /* regular file */
    }
    return 0;
}

/* ------------------------------------------------------------------ */
/* Path check: should this open() go to VFS?                           */
/* ------------------------------------------------------------------ */
bool vfs_is_virtual_path(const char *path)
{
    if (!path) return false;
    /* Also virtual if path exists in mounted ISO */
    if (iso_path_exists(path)) return true;
    return (strncmp(path, "/proc/", 6) == 0 ||
            strncmp(path, "/sys/",  5) == 0 ||
            strncmp(path, "/dev/",  5) == 0 ||
            strncmp(path, "/tmp/",  5) == 0);
}
